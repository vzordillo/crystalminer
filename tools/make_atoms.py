#!/usr/bin/env python3
"""Write a small rounded superellipsoid mesh used for exhibit atoms."""

import math
import os


ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "mods", "crystalminer", "models", "crystalminer_atom.obj")


def signed_power(value, exponent):
    return math.copysign(abs(value) ** exponent, value)


def main():
    # A high-exponent superellipsoid keeps broad flat faces while rounding edges and corners.
    vertices, normals, uvs, faces = [], [], [], []
    rings, segments = 17, 32
    for ring in range(rings):
        v = -math.pi / 2 + math.pi * ring / (rings - 1)
        for segment in range(segments):
            u = 2 * math.pi * segment / segments
            cv, sv, cu, su = math.cos(v), math.sin(v), math.cos(u), math.sin(u)
            normal = (signed_power(cv * cu, 0.30), signed_power(sv, 0.30), signed_power(cv * su, 0.30))
            length = math.sqrt(sum(axis * axis for axis in normal))
            normal = tuple(axis / length for axis in normal)
            # Slightly smaller than a node leaves a visible gap between atoms.
            vertices.append(tuple(0.46 * signed_power(value, 0.75) for value in normal))
            normals.append(normal)
            uvs.append((segment / segments, ring / (rings - 1)))
    for ring in range(rings - 1):
        for segment in range(segments):
            a = ring * segments + segment
            b = ring * segments + (segment + 1) % segments
            c = (ring + 1) * segments + (segment + 1) % segments
            d = (ring + 1) * segments + segment
            faces.append((a, b, c, d))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as obj:
        obj.write("# Rounded crystalminer exhibit atom; generated by tools/make_atoms.py\n")
        for x, y, z in vertices: obj.write("v %.6f %.6f %.6f\n" % (x, y, z))
        for x, y in uvs: obj.write("vt %.6f %.6f\n" % (x, y))
        for x, y, z in normals: obj.write("vn %.6f %.6f %.6f\n" % (x, y, z))
        for a, b, c, d in faces:
            obj.write("f %d/%d/%d %d/%d/%d %d/%d/%d %d/%d/%d\n" %
                      (a + 1, a + 1, a + 1, b + 1, b + 1, b + 1,
                       c + 1, c + 1, c + 1, d + 1, d + 1, d + 1))


if __name__ == "__main__":
    main()
