#!/usr/bin/env python3
"""Writes mods/crystalminer/exhibit_elements.lua: Jmol colour and covalent radius for every element.

Colours: the Jmol scheme, http://jmol.sourceforge.net/jscolors/ (values as in ASE's ase/data/colors.py).
Radii: B. Cordero et al., Dalton Trans. 2008, 2832-2838, DOI 10.1039/B801115J (values as in ASE's
ase/data/__init__.py). Neither the CIF nor the MPContribs record carries colours or radii, so these
published tables are the only source; nothing is invented here.

Usage: python3 tools/make_element_tables.py ase_colors.py ase_data_init.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def block(text, name):
	start = text.index(name)
	return text[text.index("[", start):text.index("\n    ]", start)]


def main(colors_path, data_path):
	colors_src = Path(colors_path).read_text()
	data_src = Path(data_path).read_text()
	symbols = re.findall(r"'([A-Za-z]{1,2})'", block(data_src, "chemical_symbols = ["))
	symbols = symbols[1:] if symbols and symbols[0] == "X" else symbols
	rgb = re.findall(r"\(([\d.]+), ([\d.]+), ([\d.]+)\),\s*#\s*(\S+)", block(colors_src, "jmol_colors = np.array"))
	radii = re.findall(r"([\d.]+|_R_DUMMY),\s*#\s*(\S+)", block(data_src, "covalent_radii = np.array"))
	by_colour = {name: tuple(round(float(v) * 255) for v in c[:3]) for *c, name in rgb}
	by_radius = {name: float(v) for v, name in radii if v != "_R_DUMMY"}
	lines = [
		"-- Jmol element colours and Cordero covalent radii (Angstrom). Generated by tools/make_element_tables.py;",
		"-- see that file for the sources. Neither the CIF nor the MPContribs record carries colours or radii.",
		"return {",
	]
	for sym in symbols:
		if sym in by_colour and sym in by_radius:
			r, g, b = by_colour[sym]
			lines.append('\t%s = { hex = "#%02X%02X%02X", radius = %.2f },' % (sym, r, g, b, by_radius[sym]))
	lines.append("}")
	out = ROOT / "mods" / "crystalminer" / "exhibit_elements.lua"
	out.write_text("\n".join(lines) + "\n")
	print("wrote", out, len(lines) - 4, "elements")


if __name__ == "__main__":
	main(*sys.argv[1:3])
